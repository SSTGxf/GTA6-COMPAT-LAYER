//! HLSL compute-shader emission for the mesh-as-compute geometry layer.
//!
//! Generates the compute shader that turns a meshlet table into an index
//! buffer and draw args, per the retargeted contract: 128 threads per
//! group, one meshlet per group, fixed 128 verts / 128 prims, no atomic
//! claim. The host precomputes the per-meshlet vertex base (the prefix
//! sum of vertex counts) and the total primitive count and uploads them;
//! the shader reads its meshlet's base from the bases buffer and the
//! total from the constants.
//!
//! The vertex interpolant write is generated as a stub (writes zeros)
//! until the per-shader attribute fetch is lifted from the DXIL. The
//! geometry layer (index buffer + draw args) is fully implemented and
//! is what this module verifies.

/// Generates the HLSL compute shader for the geometry layer.
///
/// `out_floats_per_vertex` is the mesh shader's output interpolant
/// count per vertex (9 for the menu shader, 56 for world shader
/// 093c64546c55554e). The shader writes that many floats per vertex
/// into the output vertex buffer; the interpolant values are a stub
/// until the DXIL lift fills them in.
pub fn emit_geometry_hlsl(out_floats_per_vertex: usize) -> String {
    format!(
        r#"// Mesh-as-compute geometry layer (generated by victory-mesh).
// 128 threads/group, one meshlet/group. Host supplies the per-meshlet
// vertex bases (prefix sums) and the total primitive count.
// Vertex interpolants are a stub (zeros) until the DXIL lift fills them.

ByteAddressBuffer MeshletTable : register(t0);
ByteAddressBuffer VertexData : register(t1);
ByteAddressBuffer MeshletBases : register(t2);
RWByteAddressBuffer OutVerts : register(u0);
RWByteAddressBuffer OutIndices : register(u1);
RWByteAddressBuffer OutDrawArgs : register(u2);

cbuffer Constants : register(b0)
{{
    uint TotalPrims;
}};

static const uint OUT_FLOATS_PER_VERTEX = {out_floats}u;

[numthreads(128, 1, 1)]
void main(uint3 groupId : SV_GroupID, uint threadId : SV_GroupThreadID)
{{
    uint meshletIdx = groupId.x;
    uint tid = threadId.x;

    uint header0 = MeshletTable.Load(0);
    uint header1 = MeshletTable.Load(4);
    uint N = header0 & 0x1FFFFu;
    uint payloadBase = 12u + N * 16u;

    uint recOff = 12u + meshletIdx * 16u;
    uint w0 = MeshletTable.Load(recOff);
    uint w1 = MeshletTable.Load(recOff + 4u);
    uint vc = (w0 & 127u) + 1u;
    uint pc = ((w0 >> 7u) & 127u) + 1u;
    uint vtxTable = (((w0 >> 14u) & 1u) << 16u) | (w1 & 0xFFFFu);
    uint primTable = (((w0 >> 15u) & 1u) << 16u) | (w1 >> 16u);

    // Vertex base for this meshlet (prefix sum, supplied by the host).
    uint vbase = MeshletBases.Load(meshletIdx * 4u);

    // One vertex per thread: read its index from the vertex-index table.
    // The interpolant fetch is a stub (zeros) until the DXIL lift.
    if (tid < vc)
    {{
        uint byteAddr = payloadBase + (vtxTable << 1u) + (header1 << 2u) + tid * 2u;
        uint word = MeshletTable.Load(byteAddr & ~3u);
        uint vtxIdx = (byteAddr & 2u) != 0u ? (word >> 16u) : (word & 0xFFFFu);
        uint outVert = (vbase + tid) * OUT_FLOATS_PER_VERTEX * 4u;
        // TODO(DXIL lift): fetch the attributes for vtxIdx from VertexData
        // and write the full interpolant set. Stub writes zeros.
        for (uint f = 0u; f < OUT_FLOATS_PER_VERTEX; f++)
        {{
            OutVerts.Store(outVert + f * 4u, 0u);
        }}
        // Keep the index live so the load is not dead-code eliminated.
        OutVerts.Store(outVert, vtxIdx);
    }}

    // One primitive per thread: unpack 3x7-bit indices, rebase, write.
    if (tid < pc)
    {{
        uint wordAddr = payloadBase + (primTable + tid) * 4u;
        uint packed = MeshletTable.Load(wordAddr);
        uint v0 = packed & 127u;
        uint v1 = (packed >> 7u) & 127u;
        uint v2 = (packed >> 14u) & 127u;
        uint outIdx = (meshletIdx * 128u + tid) * 12u;
        OutIndices.Store(outIdx, v0 + vbase);
        OutIndices.Store(outIdx + 4u, v1 + vbase);
        OutIndices.Store(outIdx + 8u, v2 + vbase);
    }}

    // Draw args, written once by thread 0 of group 0.
    if (meshletIdx == 0u && tid == 0u)
    {{
        OutDrawArgs.Store(0u, TotalPrims * 3u);
        OutDrawArgs.Store(4u, 1u);
        OutDrawArgs.Store(8u, 0u);
        OutDrawArgs.Store(12u, 0u);
        OutDrawArgs.Store(16u, 0u);
    }}
}}
"#,
        out_floats = out_floats_per_vertex
    )
}

/// Generates the HLSL compute shader for the MENU mesh shader
/// (`d4111a6e6ea49d91`), with the real interpolant lift.
///
/// Same geometry layer as [`emit_geometry_hlsl`] (9 floats per vertex),
/// but the vertex interpolants are computed by the lift in
/// [`crate::interpolant`] instead of the zeros stub. The shader takes one
/// extra input, `CBufferHeap` (register t3): the 64 KiB heap cbuffer
/// (handle `%483`) that holds the transform rows and the format id. The
/// host supplies it; see `MESH-INTERPOLANT-LIFT-FINDINGS.md`.
pub fn emit_menu_hlsl() -> String {
    let interp = crate::interpolant::emit_menu_interpolant_block();
    format!(
        r#"// Mesh-as-compute, menu shader (generated by victory-mesh).
// 128 threads/group, one meshlet/group. Host supplies the per-meshlet
// vertex bases (prefix sums), the total primitive count, and the 64 KiB
// heap cbuffer (CBufferHeap, t3). Vertex interpolants are the DXIL lift
// (see crate::interpolant), not a stub.

ByteAddressBuffer MeshletTable : register(t0);
ByteAddressBuffer VertexData : register(t1);
ByteAddressBuffer MeshletBases : register(t2);
ByteAddressBuffer CBufferHeap : register(t3);
RWByteAddressBuffer OutVerts : register(u0);
RWByteAddressBuffer OutIndices : register(u1);
RWByteAddressBuffer OutDrawArgs : register(u2);

cbuffer Constants : register(b0)
{{
    uint TotalPrims;
}};

static const uint OUT_FLOATS_PER_VERTEX = 9u;

[numthreads(128, 1, 1)]
void main(uint3 groupId : SV_GroupID, uint threadId : SV_GroupThreadID)
{{
    uint meshletIdx = groupId.x;
    uint tid = threadId.x;

    uint header0 = MeshletTable.Load(0);
    uint header1 = MeshletTable.Load(4);
    uint N = header0 & 0x1FFFFu;
    uint payloadBase = 12u + N * 16u;

    uint recOff = 12u + meshletIdx * 16u;
    uint w0 = MeshletTable.Load(recOff);
    uint w1 = MeshletTable.Load(recOff + 4u);
    uint vc = (w0 & 127u) + 1u;
    uint pc = ((w0 >> 7u) & 127u) + 1u;
    uint vtxTable = (((w0 >> 14u) & 1u) << 16u) | (w1 & 0xFFFFu);
    uint primTable = (((w0 >> 15u) & 1u) << 16u) | (w1 >> 16u);

    // Vertex base for this meshlet (prefix sum, supplied by the host).
    uint vbase = MeshletBases.Load(meshletIdx * 4u);

    // One vertex per thread: read its index, then the lifted interpolants.
    if (tid < vc)
    {{
        uint byteAddr = payloadBase + (vtxTable << 1u) + (header1 << 2u) + tid * 2u;
        uint word = MeshletTable.Load(byteAddr & ~3u);
        uint vtxIdx = (byteAddr & 2u) != 0u ? (word >> 16u) : (word & 0xFFFFu);
        uint outVert = (vbase + tid) * OUT_FLOATS_PER_VERTEX * 4u;
{interp}    }}

    // One primitive per thread: unpack 3x7-bit indices, rebase, write.
    if (tid < pc)
    {{
        uint wordAddr = payloadBase + (primTable + tid) * 4u;
        uint packed = MeshletTable.Load(wordAddr);
        uint v0 = packed & 127u;
        uint v1 = (packed >> 7u) & 127u;
        uint v2 = (packed >> 14u) & 127u;
        uint outIdx = (meshletIdx * 128u + tid) * 12u;
        OutIndices.Store(outIdx, v0 + vbase);
        OutIndices.Store(outIdx + 4u, v1 + vbase);
        OutIndices.Store(outIdx + 8u, v2 + vbase);
    }}

    // Draw args, written once by thread 0 of group 0.
    if (meshletIdx == 0u && tid == 0u)
    {{
        OutDrawArgs.Store(0u, TotalPrims * 3u);
        OutDrawArgs.Store(4u, 1u);
        OutDrawArgs.Store(8u, 0u);
        OutDrawArgs.Store(12u, 0u);
        OutDrawArgs.Store(16u, 0u);
    }}
}}
"#,
        interp = interp
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn geometry_hlsl_has_the_load_bearing_pieces() {
        let hlsl = emit_geometry_hlsl(9);
        // Meshlet table read + record decode.
        assert!(hlsl.contains("MeshletTable.Load(0)"));
        assert!(hlsl.contains("(w0 & 127u) + 1u"));
        assert!(hlsl.contains("((w0 >> 7u) & 127u) + 1u"));
        // 7-bit primitive unpack (not 10-bit).
        assert!(hlsl.contains("packed & 127u"));
        assert!(hlsl.contains("(packed >> 7u) & 127u"));
        assert!(hlsl.contains("(packed >> 14u) & 127u"));
        // Rebased index write + draw args.
        assert!(hlsl.contains("v0 + vbase"));
        assert!(hlsl.contains("TotalPrims * 3u"));
        // 128 threads, one meshlet per group.
        assert!(hlsl.contains("[numthreads(128, 1, 1)]"));
        // Menu shader output width.
        assert!(hlsl.contains("OUT_FLOATS_PER_VERTEX = 9u"));
    }

    #[test]
    fn geometry_hlsl_world_width() {
        let hlsl = emit_geometry_hlsl(56);
        assert!(hlsl.contains("OUT_FLOATS_PER_VERTEX = 56u"));
    }

    #[test]
    fn menu_hlsl_has_cbuffer_heap_and_real_interpolants() {
        let hlsl = emit_menu_hlsl();
        // The 64 KiB heap cbuffer input.
        assert!(hlsl.contains("ByteAddressBuffer CBufferHeap : register(t3);"));
        // Menu output width.
        assert!(hlsl.contains("OUT_FLOATS_PER_VERTEX = 9u"));
        // The lift is present (not the zeros stub).
        assert!(hlsl.contains("Menu interpolant lift"));
        assert!(hlsl.contains("CBufferHeap.Load(112)"));
        assert!(hlsl.contains("attrBase + attrStride * vtxIdx"));
        assert!(hlsl.contains("cbR0z * attrYc + cbR0y * attrXc + cbR0w"));
        assert!(hlsl.contains("OutVerts.Store(outVert + 32u, asuint(innerY))"));
        // No zeros-stub loop remains in the menu shader.
        assert!(!hlsl.contains("for (uint f = 0u; f < OUT_FLOATS_PER_VERTEX; f++)"));
        // Geometry layer still intact.
        assert!(hlsl.contains("packed & 127u"));
        assert!(hlsl.contains("TotalPrims * 3u"));
        assert!(hlsl.contains("[numthreads(128, 1, 1)]"));
    }
}
