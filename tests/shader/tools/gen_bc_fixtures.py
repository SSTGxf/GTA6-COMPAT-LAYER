# Regenerates tests/shader/sc_bc_fixtures.h from the independent texture2ddecoder package.
# Not shipped as part of the build; kept next to the probe programs so the fixtures can be
# reproduced. Run from the project root with:  python out/bcref/gen_fixtures.py
import io
import random
import texture2ddecoder as t

SEED = 20261125


def bgra_to_rgba(b):
    o = bytearray(len(b))
    for i in range(0, len(b), 4):
        o[i + 0] = b[i + 2]
        o[i + 1] = b[i + 1]
        o[i + 2] = b[i + 0]
        o[i + 3] = b[i + 3]
    return bytes(o)


def mode_of(blk):
    for m in range(7):
        if blk[0] & (1 << m):
            return m
    return 7


def force_endpoints(blk, greater):
    c0 = blk[0] | (blk[1] << 8)
    c1 = blk[2] | (blk[3] << 8)
    if greater != (c0 > c1):
        c0, c1 = c1, c0
    b = bytearray(blk)
    b[0] = c0 & 0xFF
    b[1] = c0 >> 8
    b[2] = c1 & 0xFF
    b[3] = c1 >> 8
    return bytes(b)


HEADER = """// ScarlettCompat shader pipeline - BCn decode fixtures.
// MIT. Generated by tests/shader/tools/gen_bc_fixtures.py; do not edit by hand.
//
// PROVENANCE
//   Every block below was decoded by an INDEPENDENT decoder - the texture2ddecoder
//   Python package, a separate implementation from anything in this tree - and the
//   expected texels are that decoder's output, converted from its BGRA channel order to
//   the RGBA order this project uses. Nothing here was produced by the code under test:
//   if sc_bc_decode agreed with itself, these fixtures would not exist.
//
//   Three deliberate departures from that oracle, each marked at its array:
//     - BC1 alpha is not taken from the reference. The format makes index 3 in the
//       three-colour mode transparent black; the reference leaves it opaque, so the
//       reference is an RGB-only oracle for BC1 and the harness derives alpha itself.
//     - The reference's BC3 decode picks the three-colour palette when colour0 <=
//       colour1, but BC2/BC3 colour blocks always use the four-colour mode. Its BC3
//       blocks here are therefore all four-colour, and an analytic case in the harness
//       covers the endpoint order the reference gets wrong.
//     - The reference's whole-image BC1 path disagrees with its own per-block BC1 decode,
//       so no BC1 image expectation comes from it; the BC7 image is the reference-verified
//       check of image ordering, and BC1 image coverage is structural.
//   BC2 has no entry in that decoder: its colour half is reference output and the harness
//   supplies the explicit 4-bit alpha from the block layout. BC6H is HDR and the
//   reference only emits tone-mapped RGBA8, so no BC6H texel expectations exist here.
//
//   Blocks are pseudo-random with a fixed seed. BC1 blocks alternate a forced
//   four-colour and forced three-colour endpoint order; BC7 blocks 0..7 force mode 0..7,
//   so every BPTC mode has to decode.
#pragma once

#include <cstdint>

namespace sc_bc_fixtures {
"""

out = [HEADER]


def emit_rgba(name, data, decode, comment=None):
    if comment:
        out.append(comment)
    out.append("inline const std::uint8_t %sExpected[%d][64] = {" % (name, len(data)))
    for b in data:
        px = bgra_to_rgba(decode(b, 4, 4))
        assert len(px) == 64
        out.append("    {")
        for row in range(4):
            out.append("        " + ", ".join("0x%02X" % v for v in px[row * 16:(row + 1) * 16]) + ",")
        out.append("    },")
    out.append("};")
    out.append("")


def emit_rgb(name, data, decode, comment=None):
    if comment:
        out.append(comment)
    out.append("inline const std::uint8_t %sExpectedRgb[%d][48] = {" % (name, len(data)))
    for b in data:
        px = bgra_to_rgba(decode(b, 4, 4))
        rgb = []
        for i in range(16):
            rgb.extend([px[i * 4 + 0], px[i * 4 + 1], px[i * 4 + 2]])
        assert len(rgb) == 48
        out.append("    { " + ", ".join("0x%02X" % v for v in rgb) + " },")
    out.append("};")
    out.append("")


def emit_blocks(name, data):
    out.append("inline const std::uint8_t %sBlocks[%d][%d] = {" % (name, len(data), len(data[0])))
    for b in data:
        out.append("    { " + ", ".join("0x%02X" % v for v in b) + " },")
    out.append("};")
    out.append("")

def generate():
    rng = random.Random(SEED)

    # BC1: alternating endpoint order, so both colour modes are covered.
    bc1 = [force_endpoints(rng.randbytes(8), greater=(i % 2 == 0)) for i in range(4)]
    emit_blocks('kBc1', bc1)
    emit_rgb('kBc1', bc1, t.decode_bc1,
             "// BC1: RGB only. The reference decodes index 3 of the three-colour mode as opaque\n"
             "// black; the format says transparent, so the harness checks alpha itself.")
    out.append("inline const bool kBc1BlockIsPunchThrough[4] = { false, true, false, true };")
    out.append("")

    bc1_image = [force_endpoints(rng.randbytes(8), greater=(i % 2 == 0)) for i in range(16)]
    emit_blocks('kBc1Image', bc1_image)
    emit_rgb('kBc1Image', bc1_image, t.decode_bc1,
             "// BC1 image blocks: expectations are per-block reference output in row-major order\n"
             "// (the reference's own 16x16 BC1 path does not agree with its per-block decode).")

    # BC2: explicit alpha nibbles over a four-colour block.
    bc2 = []
    for i in range(4):
        colour = force_endpoints(bc1[i], greater=True) if i < 2 else \
            force_endpoints(rng.randbytes(8), greater=True)
        a = bytearray(8)
        for p in range(16):
            nib = 0x5 if (p % 2 == 0) else 0xA
            a[p // 2] |= nib << (4 * (p % 2))
        bc2.append(bytes(a) + colour)
    emit_blocks('kBc2', bc2)
    emit_rgb('kBc2', [b[8:16] for b in bc2], t.decode_bc1,
             "// BC2: colour half as the reference decodes it (four-colour mode); alpha comes from\n"
             "// the block's explicit nibbles, which the harness checks directly.")
    out.append("")

    # BC3: colour half forced to the four-colour order the format mandates.
    bc3 = []
    for _ in range(4):
        b = bytearray(rng.randbytes(16))
        b[8:16] = force_endpoints(bytes(b[8:16]), greater=True)
        bc3.append(bytes(b))
    emit_blocks('kBc3', bc3)
    emit_rgba('kBc3', bc3, t.decode_bc3)

    bc4 = [rng.randbytes(8) for _ in range(4)]
    emit_blocks('kBc4', bc4)
    emit_rgba('kBc4', bc4, t.decode_bc4)

    bc5 = [rng.randbytes(16) for _ in range(4)]
    emit_blocks('kBc5', bc5)
    emit_rgba('kBc5', bc5, t.decode_bc5)

    bc7 = []
    for m in range(8):
        b = bytearray(rng.randbytes(16))
        b[0] = (b[0] & 0x80) | (0 if m == 7 else (1 << m))
        assert mode_of(bytes(b)) == m
        bc7.append(bytes(b))
    emit_blocks('kBc7', bc7)
    emit_rgba('kBc7', bc7, t.decode_bc7)

    image7 = []
    for i in range(16):
        b = bytearray(rng.randbytes(16))
        b[0] = (b[0] & 0x80) | (0 if i % 8 == 7 else (1 << (i % 8)))
        image7.append(bytes(b))
    emit_blocks('kBc7Image', image7)
    px = bgra_to_rgba(t.decode_bc7(b''.join(image7), 16, 16))
    assert len(px) == 16 * 16 * 4
    out.append("// One image row (16 texels, RGBA) per entry; decoded by the reference as a whole 16x16")
    out.append("// image, so this array is what pins block order and stride.")
    out.append("inline const std::uint8_t kBc7ImageExpected[16][64] = {")
    for row in range(16):
        out.append("    { " + ", ".join("0x%02X" % v for v in px[row * 64:(row + 1) * 64]) + " },")
    out.append("};")
    out.append("")

    out.append("// BC6H inputs are structural only: the harness asserts properties the format")
    out.append("// guarantees (an all-zero block is black, unsigned output is non-negative, block and")
    out.append("// image paths agree) rather than texel values, because the installed reference")
    out.append("// tone-maps HDR down to RGBA8 and cannot serve as an HDR oracle.")
    emit_blocks('kBc6h', [bytes(16), bytes([0x01] + [0] * 15), bytes([0x02] + [0] * 15),
                          bytes([0x80] + [0] * 15)])

    out.append("} // namespace sc_bc_fixtures")
    out.append("")
    io.open('tests/shader/sc_bc_fixtures.h', 'w', encoding='utf-8', newline='\n').write(
        "\n".join(out))


if __name__ == '__main__':
    generate()
    print('wrote tests/shader/sc_bc_fixtures.h (%d lines)' % len(out))
